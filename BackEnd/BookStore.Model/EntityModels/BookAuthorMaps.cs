using Microsoft.EntityFrameworkCore;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using System.Text.Json.Serialization;

namespace BookStore.Model.EntityModels
{
    /// <summary>
    /// This is an explicit 'Join Entity' (also known as an Association or Payload table). 
    /// We use this explicitly when we want to store extra information (payload) 
    /// about the relationship between a Book and an Author.
    /// </summary>
    // Reference Note: The [PrimaryKey] attribute is a modern EF Core feature (introduced in EF Core 7) 
    // that allows defining a composite primary key directly on the class using Data Annotations, 
    // bypassing the need for the Fluent API OnModelCreating configuration.
    [PrimaryKey(nameof(BookId), nameof(AuthorId))]
    public class BookAuthorMaps
    {
        #region Composite Foreign Keys

        // Reference Note: Explicitly maps these integer properties as Foreign Keys to their 
        // respective navigation properties defined at the bottom of the class.
        [ForeignKey("Book")]
        public int BookId { get; set; }

        [ForeignKey("Author")]
        public int AuthorId { get; set; }

        #endregion

        #region Payload Data

        // Reference Note: These properties represent the "Payload". 
        // If EF Core automatically generated a hidden, implicit join table for the many-to-many 
        // relationship, it would only contain the two foreign keys. By explicitly defining this class, 
        // the database can store contextual metadata about the relationship itself.

        public int AuthorOrder { get; set; }

        [MaxLength(50)]
        public string? ContributionRole { get; set; }

        // This is the 'Payload'. 
        // A hidden join table generated by EF wouldn't allow this extra column.
        public string? Description { get; set; }

        //public bool IsLeadAuthor { get; set; }

        #endregion

        #region Navigation Properties

        // Reference Note: [JsonIgnore] breaks the circular reference chain during JSON serialization 
        // (e.g., Book -> BookAuthorMaps -> Book). 
        // The 'virtual' keyword allows EF Core to dynamically override the property to support 
        // Lazy-Loading Proxies if the feature is enabled in the DbContext.

        [JsonIgnore]
        public virtual Book Book { get; set; } = null!;

        public virtual Author Author { get; set; } = null!;

        #endregion
    }
}